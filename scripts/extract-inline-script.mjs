#!/usr/bin/env node
// Extracts the inline <script> block from index.html into a plain .js file
// so ESLint (and other Node-based JS tooling) can lint it directly, without
// depending on an HTML-aware ESLint processor plugin.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const indexPath = path.join(rootDir, "index.html");
const outDir = path.join(rootDir, "lint-artifacts");
const outPath = path.join(outDir, "index.inline.js");

const html = readFileSync(indexPath, "utf8");
const scriptMatches = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)];

if (scriptMatches.length === 0) {
  throw new Error("extract-inline-script: no inline <script> block found in index.html");
}
if (scriptMatches.length > 1) {
  throw new Error(
    `extract-inline-script: expected exactly one inline <script> block, found ${scriptMatches.length}`
  );
}

const [, scriptBody] = scriptMatches[0];

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/extract-inline-script.mjs — do not edit.\n// Source of truth is the <script> block in index.html.\n${scriptBody}`
);

console.log(`Extracted inline script to ${path.relative(rootDir, outPath)}`);
